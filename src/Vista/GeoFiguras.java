    // RF02: solo los campos de la figura elegida
    public void configurarCampos(int figura) {
        lblDato1.setVisible(true);
        txtDato1.setVisible(true);
        lblDato2.setVisible(figura != 2);
        txtDato2.setVisible(figura != 2);
        lblDato3.setVisible(figura == 0);
        txtDato3.setVisible(figura == 0);

        if (figura == 0) {
            lblDato1.setText("Lado A:");
            lblDato2.setText("Lado B:");
            lblDato3.setText("Lado C:");
        } else if (figura == 1) {
            lblDato1.setText("Base:");
            lblDato2.setText("Altura:");
        } else {
            lblDato1.setText("Lado:");
        }
        limpiar();
    }

    // RF07: dos decimales y unidades
    public void mostrarResultados(double area, double perimetro) {
        txtArea.setText(String.format("%.2f u\u00B2", area));
        txtPerimetro.setText(String.format("%.2f u", perimetro));
    }

    public void mostrarError(String mensaje) {
        javax.swing.JOptionPane.showMessageDialog(this, mensaje, "Error",
                javax.swing.JOptionPane.ERROR_MESSAGE);
    }

    // RF08
    public void limpiar() {
        txtDato1.setText("");
        txtDato2.setText("");
        txtDato3.setText("");
        txtArea.setText("");
        txtPerimetro.setText("");
    }

